/// ─── 「按航向变化打点」（转弯打点）的航向过滤层 ───
///
/// 这个文件只干一件事：**把物理上不可能的一帧航向丢掉**。
///
/// ## 为什么需要它
///
/// v1.6.156 加的「转弯打点」判据一直很朴素：`|当前航向 − 上次发送时的航向| ≥ 阈值`
/// 就补一个点。问题在「当前航向」四个字上 —— 手机给的 course 在多径反射、低速、
/// 地库出口这些时候会**一帧跳几十度**（GPS 多普勒解不出方向时的典型失效），
/// 而判据把它当成一次真实的转向，于是：
///
/// * 在城市直路上每 16 分钟就会**白白多发十几个点**（`tool/sim_turn_dot.py` 里
///   的 straight_urban 场景：19 个，全部发生在直线路段，弦高改善为 0）；
/// * 更糟的是发送后 `基准 ← 当前航向`，于是这个野值被**钉成新的基准**，
///   真实航向与它差 60°，回正后又要再发一个点。
///
/// APRS 是共享信道，这些点对任何人都没有信息量。
///
/// ## 为什么不是「平滑」
///
/// 先试过窗口中位数 + 连续确认（连续 N 帧超阈值才算），仿真把它们否掉了：
///
/// * **平滑会削掉短时转弯的峰值**。一个 50° 的 S 弯（4 秒转完）经 3 点中位数后
///   峰值只剩 ≈44° —— 恰好落在用户设的 45° 之下，于是**整个弯一个点都不补**。
///   用户设的「转过 45° 就补报」这句话就不再成立了。
/// * **连续确认会把「刚好超过阈值」的转弯挡掉**：30° 的出口匝道配 30° 阈值，
///   超阈值的帧只有一帧，要求连续两帧就再也补不上点。
/// * 峰值锁存（记住最大偏离）听起来能救「转完又回正」的 S 弯，实测反而更差：
///   它把补点推到闸门打开那一刻，**点落在弯之后**（发卡弯平均弦高 8.0m → 22.4m）。
///
/// 而物理门**不改变任何可信信号**：无噪声场景下开关它，逐点、逐指标完全相同
/// （仿真的自检断言了这件事）。所以它不可能把本来就准的场景改坏。
///
/// ## 两个不变量（改这个文件前先读）
///
/// 1. **航向干净时它是直通的** —— 见上。
/// 2. **连续丢弃有上限**（[maxDrops]）：一个持续超过 [maxStepDeg]/秒的**真实**
///    转向会让每一帧都相对「上一个可信值」超限。不设上限就会**永久失明** ——
///    `_last` 卡在转向前那一帧上，之后所有帧都被判为野值，转弯打点从此彻底失效
///    （仿真里 hairpin 场景从 21 个点掉到 10 个、平均弦高翻倍）。到上限就重新
///    同步：宁可放一帧进来，也不能瞎掉。
///
/// ## 阈值 40°/秒 的来历
///
/// 取值的**两侧**都有依据（`tool/sim_turn_dot.py` 里可复现）：
///
/// * 下界：真实转向最快要算得进去。仿真里最紧的是发卡弯 22.5°/秒，叠上 GPS 航向
///   σ=7° 的噪声，一帧之差常到 22.5+2σ ≈ 36.5°。门取 25° 时这些真实转向会被自己
///   丢掉 —— hairpin 平均弦高从 9.9m 坏到 19.6m。
/// * 上界：野值要被挡住。仿真里城市直路的野值是 60°，门取 60° 就正好放行
///   （直路上又冒出 16 个无用补点）。
///
/// 40 落在 36.5 与 60 之间，而且它本身就是个物理量：**40°/秒的持续转向**已经
/// 是 20 m/s 下横向 14 m/s²，远超轮胎能提供的附着。
///
/// ## 已知局限（如实写在这里，免得以后被当成 bug）
///
/// * 只对**稠密采样**（≈1Hz，手机 GPS）有效。门是「按秒折算」的（见 [onCourse]
///   的 dt），所以佳明那种十几秒一个点的稀疏序列不会被误杀，但也不受保护。
/// * 它挡的是「不可能」而不是「不合理」：一个 35°/秒 的噪声抖法（低于门）仍然
///   可以骗过判据。要挡那种只能上平滑，而平滑的代价见上。
library;

import 'dart:math' as math;

/// 把角度差折到 0~180（最小夹角）。
///
/// 359° → 1° 是转了 2°，不是 358°。不折的话「几乎没转」会被判成「转了大半圈」，
/// 于是每个点都触发转弯打点。
double fold180(double deg) {
  var d = deg.abs() % 360.0;
  if (d > 180.0) d = 360.0 - d;
  return d;
}

class TurnDotDetector {
  /// 航向变化的物理上限（**度/秒**）：超过它的一帧按野值丢掉。
  ///
  /// 40°/秒 ≈ 20 m/s 下横向 14 m/s²，比轮胎能提供的附着大得多，
  /// 所以「一帧就转这么多」在物理上不可能是真的转向。取值依据见文件头注释。
  static const double maxStepDeg = 40.0;

  /// 连续丢多少帧之后**强制重新同步**（见文件头「两个不变量」第 2 条）。
  static const int maxDrops = 3;

  double? _last;        // 上一个「可信」航向
  DateTime? _lastAt;    // 它是什么时候来的（用来把门按 dt 折算）
  double? _ref;         // 基准航向 = 上次**真的发出去**时的可信航向
  int _drops = 0;

  /// 自基准（上次真的发出去）以来，航向偏离了多少度（0~180）。
  ///
  /// 这就是上报判据读的那个量（见 `AppState.beaconTurnDeg`）。没喂过航向、
  /// 或还没发过信标时是 0 —— 0 不触发，与改动前的口径一致。
  double deviationDeg = 0;

  /// 上一次**被接受**的航向（野值不算），没有则为 null。供测试与日志用。
  double? get lastTrustedDeg => _last;

  /// 喂一帧航向。[at] 是这一帧的时间 —— 门按 `maxStepDeg × dt` 折算，
  /// 于是 1Hz 的 GPS 与十几秒一个点的佳明序列可以共用同一条判据。
  void onCourse(double? course, DateTime at) {
    if (course == null) return;

    final prev = _last;
    final prevAt = _lastAt;
    if (prev != null && prevAt != null) {
      final dt = at.difference(prevAt).inMilliseconds / 1000.0;
      // 采样比 1 秒还密时按 1 秒算（不要因为回调抖动把门收得比物理还紧）
      final allow = maxStepDeg * math.max(1.0, dt);
      if (fold180(course - prev) > allow) {
        _drops++;
        if (_drops < maxDrops) return;   // 丢帧，且**不动** _last
      }
    }
    _drops = 0;                          // 到上限 → 重新同步
    _last = course;
    _lastAt = at;

    final base = _ref;
    if (base == null) {
      _ref = course;
      deviationDeg = 0;
      return;
    }
    deviationDeg = fold180(course - base);
  }

  /// 真的发出去之后调用（见 `AppState._sendBeaconNow`）：基准 ← 上一个可信航向，
  /// 判据归零。
  ///
  /// 基准取 [_last] 而**不是**调用方手里的原始航向：发送那一刻的航向若正好是野值，
  /// 拿它当基准就会把野值钉死 —— 之后真实航向与它差 60°，凭空触发一轮补点。
  /// 野值不该有机会成为基准，这与「丢帧」是同一件事的两面。
  void markSent() {
    final last = _last;
    if (last != null) _ref = last;
    deviationDeg = 0;
  }
}
